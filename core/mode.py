def current() -> str:
    m = settings.game_mode()
    return m if m in (KILLER, PAPARAZZI) else DEFAULT_MODE


def set_current(mode: str):
    settings.set_game_mode(mode if mode in (KILLER, PAPARAZZI) else DEFAULT_MODE)


def _idx() -> int:
    return 0 if current() == KILLER else 1


def term(key: str) -> str:
    return TERMS[key][_idx()]


def t(key: str, **fmt) -> str:
    """Текст сообщения для текущего режима с подстановкой плейсхолдеров."""
    tpl = MESSAGES[key][_idx()]
    return tpl.format(**fmt) if fmt else tpl


def is_killer() -> bool:
    return current() == KILLER


def pairs():
    """[(раздел, ключ, killer, paparazzi)] — для генерации файла MODE_MESSAGES.txt."""
    out = []
    for key, (k, p) in TERMS.items():
        out.append(("term", key, k, p))
    for key, (k, p) in MESSAGES.items():
        out.append(("message", key, k, p))
    return out
